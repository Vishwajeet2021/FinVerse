"""Creates docker/.env with freshly generated local secrets (never committed).

    python scripts/gen_env.py            # refuses to overwrite an existing file
    python scripts/gen_env.py --force    # regenerates (existing databases keep the OLD
                                         # passwords until you recreate the volume)

Values use `secrets`, so they are cryptographically random. docker/.env.example documents
every variable without any real value.
"""
import base64
import pathlib
import secrets
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "docker" / ".env"
SERVICES = ["AUTH", "CUSTOMER", "TRANSACTION", "ACCOUNT", "WALLET", "PAYMENT", "NOTIFICATION", "AUDIT", "FRAUD"]


def main() -> None:
    if TARGET.exists() and "--force" not in sys.argv:
        raise SystemExit(f"{TARGET} already exists; pass --force to regenerate it")
    lines = [
        "# Generated by scripts/gen_env.py. Local development only. Never commit this file.",
        f"POSTGRES_PASSWORD={secrets.token_hex(16)}",
    ]
    lines += [f"{name}_DB_PASSWORD={secrets.token_hex(16)}" for name in SERVICES]
    lines += [
        f"SERVICE_AUTH_KEY={secrets.token_hex(32)}",
        f"CUSTOMER_PAN_ENCRYPTION_KEY={base64.b64encode(secrets.token_bytes(32)).decode()}",
        f"GRAFANA_ADMIN_PASSWORD={secrets.token_urlsafe(16)}",
    ]
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TARGET}")


main()
